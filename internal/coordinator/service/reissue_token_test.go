// TestReissueBotToken_AgentOwnerlessRejected: an agent whose ParentID
// is nil (edge case — not producible via RegisterBot, but defensible)
// must be rejected.
func TestReissueBotToken_AgentOwnerlessRejected(t *testing.T) {
	s := newReissueStore(t)
	caller := makeHuman(t, s, "alice", "alice-tok")
	// Create a parentless agent directly via plan mutation.
	_, err := s.ApplyPlan(store.Plan{
		Version: store.TestEngineVersion,
		Mutations: []store.Mutation{
			store.CreateCitizen{
				Citizen: store.CitizenRecord{
					Username: "orphan-bot",
					Name:     "orphan-bot",
					Email:    "orphan-bot@test.local",
					Kind:     store.CitizenKindAgent,
					// ParentID intentionally nil
				},
				Token: "orphan-tok",
			},
		},
	})
	if err != nil {
		t.Fatalf("create orphan agent: %v", err)
	}

	_, err = ReissueBotToken(s, caller, "orphan-bot", "")
	if err == nil {
		t.Fatal("expected ErrForbidden, got nil")
	}
	if !errors.Is(err, ErrForbidden) {
		t.Errorf("expected ErrForbidden, got %v", err)
	}
}

// TestReissueBotToken_LabelPreserved: the supplied label lands on the
// new token row (audit path).
func TestReissueBotToken_LabelPreserved(t *testing.T) {
	s := newReissueStore(t)
	owner := makeHuman(t, s, "alice", "alice-tok")
	agent := makeAgent(t, s, owner, "dev-bot")

	resp, err := ReissueBotToken(s, owner, "dev-bot", "ci-server")
	if err != nil {
		t.Fatalf("ReissueBotToken: %v", err)
	}

	tokens, err := s.ListTokensByCitizen(agent.ID)
	if err != nil {
		t.Fatalf("list tokens: %v", err)
	}
	var found bool
	for _, tok := range tokens {
		if tok.Token == resp.Token && tok.Label == "ci-server" {
			found = true
		}
	}
	if !found {
		t.Errorf("new token with label %q not found in token list: %+v", "ci-server", tokens)
	}
}
